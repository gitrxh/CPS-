"""Trajectory-level policy scoring for CPS v2.

The original CPS scores individual actions. This module provides trajectory
likelihood evaluation so projection can operate on executable suffixes:

    log p(tau|h) = sum_t log p(a_t | h_t)

The environment remains the authority for history transitions.
"""

from __future__ import annotations

from typing import Any


class TrajectoryPolicyScorer:
    """Wrapper around a causal policy for suffix trajectory scoring."""

    def __init__(self, policy: Any):
        self.policy = policy

    def score_trajectory(
        self,
        task: str,
        history: list[dict],
        observation: str,
        admissible_commands: list[str],
        trajectory: list[str],
    ) -> dict:
        """Score a complete executable suffix.

        Unlike action scoring, every action updates the causal history. The
        caller should provide trajectories generated by the simulator so that
        observations are never hallucinated.
        """
        total = 0.0
        token_count = 0
        per_step = []

        current_history = list(history)
        current_observation = observation
        current_commands = list(admissible_commands)

        for action in trajectory:
            scores = self.policy.score_actions(
                task,
                current_history,
                current_observation,
                current_commands,
                [action],
            )
            item = scores[0]
            total += float(item["logprob"])
            token_count += int(item["token_count"])
            per_step.append(item)

            # Transition update must be supplied by the real environment.
            # We intentionally do not fabricate observations here.
            current_history.append({
                "observation": current_observation,
                "action": action,
            })

        return {
            "trajectory": trajectory,
            "logprob": total,
            "token_count": token_count,
            "mean_logprob": total / max(token_count, 1),
            "per_step": per_step,
        }
