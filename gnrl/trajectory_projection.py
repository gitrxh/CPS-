"""Causal trajectory projection utilities for CPS v2.

This module extends action-level conditional sampling into trajectory-level
projection. It intentionally does not modify the existing pipeline. It provides
small reusable primitives:

1. collect real simulator rollouts after candidate actions;
2. score complete suffix trajectories under a causal policy;
3. perform constrained projection over executable trajectories.

The key difference from action-only CPS is that the object being selected is
(a_t, ..., a_T) rather than only a_t.
"""

from __future__ import annotations

from dataclasses import dataclass
from math import exp
from typing import Callable, Iterable


@dataclass
class ProjectedTrajectory:
    actions: list[str]
    success: bool
    logprob: float
    score: float = 0.0


class CausalTrajectoryProjector:
    """Finite-support causal trajectory projection.

    Given executable candidate suffixes generated by the environment, select
    learner-compatible successful trajectories instead of only selecting the
    first action. This is a lightweight implementation intended for ALFWorld
    experiments.
    """

    def __init__(self, temperature: float = 1.0):
        if temperature <= 0:
            raise ValueError("temperature must be positive")
        self.temperature = temperature

    @staticmethod
    def normalize_logprobs(items: list[ProjectedTrajectory], temperature: float = 1.0):
        if not items:
            return []
        values = [x.logprob / temperature for x in items]
        m = max(values)
        weights = [exp(v - m) for v in values]
        z = sum(weights)
        return [w / z for w in weights]

    def project(
        self,
        candidates: Iterable[ProjectedTrajectory],
        require_success: bool = True,
    ) -> ProjectedTrajectory:
        """Return the learner-native trajectory from executable candidates.

        Candidates must already be generated by the real environment. Future
        observations or oracle states must not be injected here.
        """
        pool = list(candidates)
        if require_success:
            pool = [x for x in pool if x.success]
        if not pool:
            raise ValueError("No executable successful trajectories available")

        probs = self.normalize_logprobs(pool, self.temperature)
        return pool[max(range(len(pool)), key=lambda i: probs[i])]


def trajectory_logprob(
    actions: list[str],
    scorer: Callable[[str], float],
) -> float:
    """Compute causal trajectory likelihood.

    scorer should return log p(a_t | history). The caller controls history
    updates because the environment transition must remain authoritative.
    """
    return float(sum(scorer(action) for action in actions))
