"""Generate causal trajectory projection samples.

This module defines the data contract for CPS v2. It intentionally separates
candidate generation, simulator execution, and projection. A trajectory is
accepted only after the environment has generated the successor observations.
"""

from __future__ import annotations

from dataclasses import dataclass, asdict
import json
from pathlib import Path


@dataclass
class TrajectorySample:
    task: str
    history: list[dict]
    observation: str
    admissible_commands: list[str]
    actions: list[str]
    success: bool
    source: str = "causal_rollout"

    def to_dict(self):
        return asdict(self)


def build_sample(task, history, observation, admissible_commands, transitions, success):
    """Convert simulator transitions into a projection sample.

    `transitions` must be generated by the real environment. Stored future
    observations are metadata only and are not used as model inputs.
    """
    return TrajectorySample(
        task=task,
        history=list(history),
        observation=observation,
        admissible_commands=list(admissible_commands),
        actions=[x["action"] for x in transitions],
        success=bool(success),
    )


def save_jsonl(samples, output):
    path = Path(output)
    with path.open("w", encoding="utf-8") as f:
        for sample in samples:
            f.write(json.dumps(sample.to_dict(), ensure_ascii=False) + "\n")
