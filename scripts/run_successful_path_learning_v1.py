    signal.signal(signal.SIGHUP, termination)
    queue = Queue(args.adoption_json)
    try:
        queue.main()
    except BaseException as error:
        queue.update("stopped_needs_astra_review", complete=False, error=f"{type(error).__name__}: {error}",
                     interpretation="No scientific comparison is authorized from an incomplete batch.")
        return 1
    return 0


