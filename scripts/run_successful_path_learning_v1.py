def require(value, reason):
    if not value:
        raise RuntimeError(reason)


def read_json(path):
    return json.loads(Path(path).read_text(encoding="utf-8-sig"))


def rows(path):
    return [json.loads(line) for line in Path(path).read_text(encoding="utf-8-sig").splitlines() if line.strip()]


def sha256(path):
    value = hashlib.sha256()
    with Path(path).open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            value.update(chunk)
    return value.hexdigest()


def atomic_json(path, value):
    path = Path(path)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(json.dumps(value, indent=2, ensure_ascii=False), encoding="utf-8")
    temporary.replace(path)


def utc():
    return datetime.now(timezone.utc).isoformat()


def safe_relative(name, root=ROOT):
    path = Path(name)
    require(not path.is_absolute() and ".." not in path.parts and path.as_posix() == name,
            "Expected normalized workspace-relative path: " + str(name))
    resolved = (root / path).resolve()
    require(resolved.is_relative_to(root.resolve()), "Path escapes workspace")
    return resolved


def source_inventory(root=ROOT):
    return sorted([p.relative_to(root).as_posix() for folder in ("gnrl", "scripts", "tests")
                   for p in (root / folder).rglob("*.py")] + [PLAN, SEARCH])


def verify_hashes(hashes, root=ROOT):
    for name, expected in hashes.items():
        path = safe_relative(name, root)
        require(path.is_file() and sha256(path) == expected, "Missing/changed adopted file: " + name)


def verify_model(provenance, model=MODEL, full_inventory=None):
    require(provenance.get("model_path") == MODEL and provenance.get("algorithm") == "SHA256", "Wrong model provenance")
    inventory = full_inventory or provenance
    require(inventory.get("model_path") == MODEL and inventory.get("algorithm") == "SHA256", "Wrong full model inventory")
    folder = Path(model)
    expected = {f["name"]: f for f in inventory["files"]}
    actual = {p.relative_to(folder).as_posix() for p in folder.rglob("*") if p.is_file()}
    require(len(expected) == len(inventory["files"]) and actual == set(expected), "Model file inventory changed")
    for core in provenance["files"]:
        require(core["name"] in expected and all(core[k] == expected[core["name"]][k] for k in ("name", "bytes", "sha256")), "Full inventory differs from frozen core model provenance")
    require({"config.json", "tokenizer_config.json", "tokenizer.json", "model.safetensors.index.json"} <= actual,
            "Incomplete model/tokenizer provenance")
    for name, record in expected.items():
        require(not Path(name).is_absolute() and ".." not in Path(name).parts, "Unsafe model manifest path")
        path = folder / name
        require(path.stat().st_size == record["bytes"] and sha256(path) == record["sha256"], "Model bytes changed: " + name)
    weights = read_json(folder / "model.safetensors.index.json")["weight_map"]
    require(weights and set(weights.values()) <= actual, "Unbound model weight shards")


