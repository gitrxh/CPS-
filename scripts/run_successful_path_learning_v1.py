class Queue:
    def __init__(self, adoption_path):
        self.started = time.monotonic()
        self.deadline = self.started + 28800
        self.adoption_path = Path(adoption_path).resolve()
        self.adoption_hash = sha256(self.adoption_path)
        self.adopted = validate_adoption(self.adoption_path)
        self.paths = self.adopted["output_paths"]
        self.locks = dict(self.adopted["file_sha256"])
        self.folder = ROOT / self.paths["queue"]
        self.folder.mkdir(parents=True, exist_ok=False)
        self.state = {"started_utc": utc(), "physical_gpu": 2, "stages": [], "complete": False,
                      "adoption_sha256": self.adoption_hash, "max_queue_seconds": 28800}
        self.env = dict(os.environ, CUDA_VISIBLE_DEVICES="", HF_HUB_OFFLINE="1", HF_DATASETS_OFFLINE="1",
                        PYTHONUNBUFFERED="1", TOKENIZERS_PARALLELISM="false")
        self.env.pop("GNRL_GPU_GUARD", None)
        self.python = str(ROOT / ".venv/bin/python")
        self.game_locks = {Path(name): value for name, value in self.adopted["original_file_sha256"].items()}
        self.directory_locks = {}

    def update(self, stage, **extra):
        self.state.update(current_stage=stage, updated_utc=utc(), **extra)
        atomic_json(self.folder / "status.json", self.state)
        print(json.dumps({"stage": stage, **extra}), flush=True)

    def lock(self, paths):
        for path in paths:
            path = Path(path)
            name = path.relative_to(ROOT).as_posix()
            value = sha256(path)
            require(name not in self.locks or self.locks[name] == value, "Artifact changed before lock")
            self.locks[name] = value
        atomic_json(self.folder / "locked_sha256.json", self.locks)

    def lock_directory(self, folder):
        paths = sorted(p for p in folder.rglob("*") if p.is_file())
        require(paths, "Empty artifact directory")
        self.lock(paths)
        self.directory_locks[folder] = {p.relative_to(folder).as_posix() for p in paths}

    def verify(self):
        require(time.monotonic() < self.deadline, "Eight-hour queue budget exhausted")
        require(sha256(self.adoption_path) == self.adoption_hash, "Learning adoption changed")
        require(source_inventory() == self.adopted["source_inventory"], "Source inventory changed")
        verify_hashes(self.locks)
        verify_model(read_json(ROOT / PROVENANCE), full_inventory=read_json(ROOT / MODEL_INVENTORY))
        for path, expected in self.game_locks.items():
            require(sha256(path) == expected, "Original game/metadata changed: " + str(path))
        for folder, expected in self.directory_locks.items():
            require({p.relative_to(folder).as_posix() for p in folder.rglob("*") if p.is_file()} == expected, "Locked artifact inventory changed")
        require(time.monotonic() < self.deadline, "Eight-hour queue budget exhausted during input verification")

    def wait_gpu(self):
        from scripts.launch_gpu import resolve_devices
        self.update("waiting_for_gpu2")
        while time.monotonic() < self.deadline:
            smi = subprocess.check_output(["nvidia-smi", "--query-gpu=index,uuid,name,memory.used", "--format=csv,noheader,nounits"], text=True, timeout=30)
            active = subprocess.check_output(["nvidia-smi", "--query-compute-apps=gpu_uuid", "--format=csv,noheader,nounits"], text=True, timeout=30)
            try:
                resolve_devices([2], list(csv.reader(io.StringIO(smi))), active_uuids={s.strip() for s in active.splitlines()})
                return
            except RuntimeError:
                time.sleep(min(20, max(0, self.deadline - time.monotonic())))
        raise TimeoutError("GPU2 unavailable within fixed budget")

    def run(self, name, arguments, wall=7200, gpu=True):
        self.verify()
        if gpu:
            self.wait_gpu()
        self.verify()
        command = [self.python, *arguments]
        if gpu:
            command = [self.python, "scripts/launch_gpu.py", "--gpus", "2", "--receipt", str(self.folder / (name + "_gpu.json")), "--", *command]
        began = time.monotonic()
        record = {"name": name, "command": command, "started_utc": utc()}
        self.state["stages"].append(record)
        self.update(name)
        process, ticks = None, None
        with (self.folder / (name + ".stdout.log")).open("xb") as out, (self.folder / (name + ".stderr.log")).open("xb") as err:
            try:
                process = subprocess.Popen(command, cwd=ROOT, env=self.env, stdin=subprocess.DEVNULL,
                                           stdout=out, stderr=err, start_new_session=True)
                identity = process_record(process.pid)
                require(identity is not None and identity["session"] == process.pid, "Cannot establish owned subprocess session")
                ticks = identity["start_ticks"]
                record.update(pid=process.pid, start_ticks=ticks, owned_session=process.pid)
                self.update(name)
                code = process.wait(timeout=min(wall, max(0.1, self.deadline - time.monotonic())))
            finally:
                if process is not None:
                    # A repeated TERM/INT during cleanup must not strand children.
                    old_mask = signal.pthread_sigmask(signal.SIG_BLOCK, {signal.SIGTERM, signal.SIGINT, signal.SIGHUP})
                    try:
                        cleanup_owned(process, ticks)
                    finally:
                        signal.pthread_sigmask(signal.SIG_SETMASK, old_mask)
                record.update(returncode=process.returncode if process else None, elapsed_seconds=time.monotonic() - began, owned_cleanup_complete=True)
                self.update(name)
        require(code == 0, "Technical stage failure: " + name)
        self.verify()

    def train(self, arm, audit):
        data = self.paths["selection"] + "/" + DATA_FILES[arm]
        checkpoint = self.paths["checkpoints"][arm]
        args = ["-m", "gnrl.train_sft", "--data", data, "--output", checkpoint, "--max-wall-seconds", "7200"]
        for key, value in TRAIN.items():
            args += ["--" + key.replace("_", "-"), str(value)]
        self.run("train_" + arm, args)
        folder = ROOT / checkpoint
        summary, config = read_json(folder / "summary.json"), read_json(folder / "config.json")
        validate_training(summary, config, self.locks[data], audit["exposures"][arm]["sampled_target_tokens"])
        require(config.get("output") == checkpoint and config.get("data") == data, "Training output/data paths differ")
        final = folder / "final"
        require((final / "adapter_config.json").is_file() and
                any((final / name).is_file() for name in ("adapter_model.safetensors", "adapter_model.bin")), "Missing final LoRA adapter")
        adapter = read_json(final / "adapter_config.json")
        require(adapter.get("base_model_name_or_path") == MODEL and adapter.get("r") == 16 and adapter.get("lora_alpha") == 32,
                "Final adapter base/config differs")
        require(read_json(final / "training_state.json").get("optimizer_steps") == 100, "Final checkpoint is not step100")
        self.lock_directory(folder)
        self.state.setdefault("trained_arms", []).append(arm)
        self.update("trained_" + arm)

    def evaluate(self, arm):
        require(self.state.get("trained_arms") == list(ARMS), "All three final adapters must finish before any evaluation")
        checkpoint = self.paths["checkpoints"][arm] + "/final"
        evaluation = self.paths["evaluations"][arm]
        args = ["-m", "gnrl.evaluate", "--adapter", checkpoint, "--games-json", DEV_MANIFEST, "--output", evaluation, "--max-wall-seconds", "7200"]
        for key, value in EVAL.items():
            args += ["--" + key.replace("_", "-"), str(value)]
        self.run("eval_" + arm, args)
        folder = ROOT / evaluation
        summary, episodes, config = read_json(folder / "summary.json"), rows(folder / "episodes.jsonl"), read_json(folder / "config.json")
        validate_evaluation(summary, episodes, config, read_json(ROOT / DEV_MANIFEST)["games"], checkpoint, self.locks[DEV_MANIFEST])
        self.lock_directory(folder)
        self.state.setdefault("evaluated_arms", []).append(arm)
        self.update("evaluated_" + arm, completed_episode_count=24)

    def main(self):
        self.verify()
        pools, coverage = validate_acquisition(self.adopted)
        atomic_json(self.folder / "cpu_gate_recomputed.json", coverage)
        self.lock([self.folder / "cpu_gate_recomputed.json"])
        for pool in pools:
            game = Path(pool["gamefile"])
            for path in (game, game.with_name("traj_data.json")):
                require(self.game_locks[path] == sha256(path), "Adopted training file changed")
        dev = read_json(ROOT / DEV_MANIFEST)
        require(dev.get("split") == "valid_seen" and len(dev["games"]) == len(set(dev["games"])) == 24, "Wrong development cohort")
        for game in dev["games"]:
            require(sha256(game) == dev["game_sha256"][game], "Frozen development game changed")
            require(self.game_locks[Path(game)] == dev["game_sha256"][game], "Adoption differs from frozen dev game")
        atomic_json(self.folder / "original_game_locks.json", {str(k): v for k, v in self.game_locks.items()})
        self.lock([self.folder / "original_game_locks.json"])
        self.select(pools)
        audit = self.audit(pools)
        for arm in ARMS:
            self.train(arm, audit)
        atomic_json(self.folder / "all_training_complete.json", {"arms": list(ARMS), "checkpoint_sha256": {
            name: value for name, value in self.locks.items() if name.startswith("checkpoints/")}, "recorded_utc": utc()})
        self.lock([self.folder / "all_training_complete.json"])
        for arm in ARMS:
            self.evaluate(arm)
        self.finalize()
        self.verify()
        self.update("needs_astra_complete_result_review", complete=True,
                    note="Single exploratory three-arm batch ended. No automatic confirmation, extra seeds, tuning or unseen evaluation.")

    def select(self, pools):
        """Selector interface is fixed below; complete scores precede any audit/train."""
        from gnrl.successful_path_selection_v1 import validate_selection_artifacts
        cpu = self.adopted["accepted_cpu_output"]
        self.run("select", ["-m", "gnrl.successful_path_selection_v1", "--acquisition-dir", cpu,
            "--output", self.paths["selection"], "--adoption-json", str(self.adoption_path),
            "--model-provenance", PROVENANCE], wall=3600)
        self.selection = validate_selection_artifacts(pools, ROOT / self.paths["selection"])
        summary = read_json(ROOT / self.paths["selection"] / "selection_summary.json")
        require(summary.get("complete") is True and summary.get("training_gate_passed") is True and len(self.selection["records"]) == 60, "Incomplete or degenerate selection")
        selected = {arm: {r["gamefile"]: r["candidates_by_arm"][arm]["candidate_id"] for r in self.selection["records"]} for arm in ARMS}
        require(all(any(selected["reference"][g] != selected[other][g] for g in selected["reference"]) for other in ("canonical", "uniform")),
                "Degenerate selector comparison: stop without redraw or training")
        self.lock_directory(ROOT / self.paths["selection"])

    def audit(self, pools):
        target = self.folder / "token_exposure_audit.json"
        self.run("token_exposure_audit", ["-m", "gnrl.successful_path_token_audit_v1", "--selection-dir", self.paths["selection"],
            "--pools", self.adopted["accepted_cpu_output"] + "/candidate_pools.jsonl", "--model", MODEL, "--output", str(target)], wall=3600, gpu=False)
        result = read_json(target)
        require(result.get("complete") is True and len(result["sampled_indices"]) == 800 and result.get("score_sft_token_mismatches") == 0, "Incomplete token audit")
        for arm in ARMS:
            for task, pool in zip(result["tasks"][arm], pools):
                require(task["action_count"] == pool["canonical_length_cost"][0], "Audit canonical action count differs")
                require(task["audited_operator_cost"] == pool["canonical_length_cost"][1], "Audit operator cost differs")
            require(result["exposures"][arm]["sampled_target_tokens"] <= 2000000, "Audit exceeds training target-token budget")
        require(result["dataset_bytes_sha256"] == {arm: self.locks[self.paths["selection"] + "/" + DATA_FILES[arm]] for arm in ARMS}, "Audit dataset hashes differ")
        self.lock([target])
        self.verify()
        return result

    def finalize(self):
        require(self.state.get("evaluated_arms") == list(ARMS), "Cannot interpret incomplete batch")
        episodes = {arm: rows(ROOT / self.paths["evaluations"][arm] / "episodes.jsonl") for arm in ARMS}
        matched, families = [], {}
        for triple in zip(*(episodes[arm] for arm in ARMS)):
            first = []
            for episode in triple:
                require(episode.get("transitions"), "Cannot establish initial observation/admissibility agreement")
                t = episode["transitions"][0]
                first.append((t["observation"], t["admissible_commands"]))
            require(first[0] == first[1] == first[2], "Initial observation/admissible lists differ")
            game = triple[0]["gamefile"]
            family = Path(game).parent.parent.name.split("-")[0]
            entry = {"gamefile": game, "family": family, **{arm: ep["success"] for arm, ep in zip(ARMS, triple)}}
            matched.append(entry)
            counts = families.setdefault(family, {"tasks": 0, **dict.fromkeys(ARMS, 0)})
            counts["tasks"] += 1
            for arm in ARMS:
                counts[arm] += entry[arm]
        require(len(families) == 6 and all(v["tasks"] == 4 for v in families.values()), "Development family composition differs")
        counts = {arm: sum(r[arm] for r in matched) for arm in ARMS}
        comparisons = {other: {"gains": sum(r["reference"] and not r[other] for r in matched),
                               "losses": sum(r[other] and not r["reference"] for r in matched),
                               "ties": sum(r["reference"] == r[other] for r in matched),
                               "rate_difference": (counts["reference"] - counts[other]) / 24} for other in ("canonical", "uniform")}
        result = {"complete": True, "successes_out_of_24": counts, "families": families, "matched_tasks": matched,
                  "reference_comparisons": comparisons, "directional_exploratory_screen": counts["reference"] > counts["canonical"] and counts["reference"] > counts["uniform"],
                  "scope": "Exploratory reused dev24, one seed; no confirmatory claim or automatic follow-up authorization",
                  "initial_observation_and_admissible_equality": True, "raw_initial_state_comparison_available": False}
        result["uniform_minus_canonical_rate"] = (counts["uniform"] - counts["canonical"]) / 24
        result["rollout_diagnostics"] = {}
        for arm in ARMS:
            attempts = [t for ep in episodes[arm] for t in ep["transitions"]]
            invalid = sum(t["policy"].get("is_admissible") is False for t in attempts)
            result["rollout_diagnostics"][arm] = {
                "invalid_actions": invalid, "action_attempts": len(attempts),
                "invalid_action_rate": invalid / len(attempts) if attempts else None,
                "all_episode_lengths_including_failures": [ep["environment_steps"] for ep in episodes[arm]],
                "training_costs": read_json(ROOT / self.paths["checkpoints"][arm] / "summary.json"),
                "evaluation_costs": read_json(ROOT / self.paths["evaluations"][arm] / "summary.json")}
        result["measured_training_exposure"] = read_json(self.folder / "token_exposure_audit.json")["exposures"]
        result["scoring_costs"] = read_json(ROOT / self.paths["selection"] / "selection_summary.json")
        result["acquisition_cost_receipts"] = {
            "accepted": self.adopted["accepted_cpu_output"] + "/summary.json",
            "failed_v1": "outputs/successful_paths_cpu_v1/summary.json"}
        atomic_json(self.folder / "complete_batch_report.json", result)
        self.lock([self.folder / "complete_batch_report.json"])


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--adoption-json", required=True, type=Path)
    args = parser.parse_args(argv)
    require(sys.platform.startswith("linux") and ROOT.resolve() == Path("/home/jsy/GNRL_20261012").resolve(), "Runtime only in chemistry project workspace")
    require(hasattr(os, "pidfd_open") and hasattr(signal, "pidfd_send_signal"), "PID-safe cleanup requires Linux pidfd support")
    require(process_record(os.getpid()) is not None, "Linux process identity is unreadable")
    probe_fd = os.pidfd_open(os.getpid())
    os.close(probe_fd)
    require((ROOT / ".venv/bin/python").is_file(), "Project environment missing")
    os.chdir(ROOT)
    def termination(signum, frame):
        raise RuntimeError("Queue received signal " + str(signum))
    signal.signal(signal.SIGTERM, termination)
