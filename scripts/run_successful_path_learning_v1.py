def process_record(pid, proc=Path("/proc")):
    try:
        raw = (proc / str(pid) / "stat").read_text()
    except FileNotFoundError:
        return None
    fields = raw[raw.rfind(")") + 2:].split()
    return {"pid": int(pid), "state": fields[0], "pgrp": int(fields[2]), "session": int(fields[3]), "start_ticks": int(fields[19])}


def owned_members(pid, start_ticks, proc=Path("/proc")):
    leader = process_record(pid, proc)
    require(leader is None or leader["start_ticks"] == start_ticks, "PID reused; refuse cleanup of unrelated process")
    result = []
    for entry in proc.iterdir():
        if not entry.name.isdigit():
            continue
        member = process_record(int(entry.name), proc)
        if member and member["session"] == pid:
            require(member["start_ticks"] >= start_ticks, "Session identity mismatch")
            if member["state"] != "Z":
                result.append(member)
    return result


def signal_member(member, sig):
    """pidfd pins kernel identity; a post-open tick check excludes PID reuse."""
    try:
        fd = os.pidfd_open(member["pid"])
    except ProcessLookupError:
        return
    try:
        actual = process_record(member["pid"])
        if actual and actual["start_ticks"] == member["start_ticks"] and actual["session"] == member["session"]:
            try:
                signal.pidfd_send_signal(fd, sig)
            except ProcessLookupError:
                pass
    finally:
        os.close(fd)


def cleanup_owned(process, start_ticks, grace=10):
    require(start_ticks is not None, "Cannot clean without recorded start ticks")
    until = time.monotonic() + grace
    while True:
        members = owned_members(process.pid, start_ticks)
        if not members:
            break
        sig = signal.SIGTERM if time.monotonic() < until else signal.SIGKILL
        for member in members:
            signal_member(member, sig)
        if time.monotonic() >= until + 5:
            raise RuntimeError("Owned subprocess session did not exit after SIGKILL")
        time.sleep(0.1)
    process.wait(timeout=5)


